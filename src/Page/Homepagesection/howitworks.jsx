function Connector({ d, color, arrow, arrowDirection = "right" }) {
  const markerPoints =
    arrowDirection === "down"
      ? `${arrow.x},${arrow.y} ${arrow.x - 7},${arrow.y - 12} ${arrow.x + 7},${arrow.y - 12}`
      : arrowDirection === "left"
        ? `${arrow.x},${arrow.y} ${arrow.x + 10},${arrow.y - 6} ${arrow.x + 10},${arrow.y + 6}`
        : `${arrow.x},${arrow.y} ${arrow.x - 10},${arrow.y - 6} ${arrow.x - 10},${arrow.y + 6}`;

  return (
    <>
      <path
        d={d}
        stroke={color}
        strokeWidth="1.8"
        strokeDasharray="5 5"
        strokeLinecap="round"
        fill="none"
      />
      <polygon points={markerPoints} fill={color} />
    </>
  );
}

